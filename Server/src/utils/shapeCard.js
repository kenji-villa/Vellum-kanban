export const shapeCard = (c) => ({
  id: c.id,
  title: c.title,
  description: c.description,
  priority: c.priority,
  dueDate: c.dueDate ? c.dueDate.toISOString().slice(0, 10) : "",
  labels: c.labels,
  assignee: c.assignee,
  assigneeId: c.assigneeId || "",
  assignedById: c.assignedById || "",
  status: c.status,
  submittedAt: c.submittedAt,
  completedAt: c.completedAt,
  comments: c.comments,
});